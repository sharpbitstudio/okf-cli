            git(repo, "init", "-q", "-b", "main")
            listOf(
                "user.name" to "t",
                "user.email" to "t@t",
                "commit.gpgsign" to "false",
                "core.autocrlf" to "false",
                "core.fsmonitor" to "false",
                "core.hooksPath" to home.resolve("no-hooks").path,
                // The tool's own git calls inherit the global config: keep ignore rules repo-only.
                "core.excludesFile" to home.resolve("empty").apply { writeText("") }.path,
            ).forEach { (key, value) -> git(repo, "config", key, value) }
        }
        assertEquals(0, run("index", "--repo=${hub.path}").code)
        listOf(hub, satA, satB).forEach { commit(it, "init", DAY_0) }
    }

    @Test
    fun `clean federation - exit 0, summary on stdout, no report and a stale one is deleted`() {
        report.apply { parentFile.mkdirs() }.writeText("stale")
        val run = xcheck()
        assertEquals(0, run.code, run.toString())
        assertEquals("", run.err)
        assertEquals(
            "okfXcheck OK: 3 repos checked, 4 cross-repo references resolved, 1 references to non-federated repos not checked, " +
                "2 Satellite Notes linked to 1 Feature Records.",
            run.out.trim(),
        )
        assertFalse(report.exists(), "a clean run removes the report")

        // The hub's own check accepts the generated Repos section.
        val check = run("check", "--repo=${hub.path}", "--strict", "--refs-strict", "--code-paths-required")
        assertEquals(0, check.code, check.toString())
        assertTrue(
            hub.resolve("docs/index.md").readText().endsWith(
                "<!-- okf:repos-start -->\n<!-- GENERATED by tool/run-okf.sh index from okf.yaml satellites — do not edit by hand. -->\n\n" +
                    "* [sat-a](https://github.com/org/sat-a/blob/main/docs/index.md) - Satellite A\n" +
                    "* [sat-b](https://github.com/org/sat-b/blob/main/doc/index.md) - Satellite B\n<!-- okf:repos-end -->\n",
            ),
        )
    }

    @Test
    fun `failures of checks a, b, c and e - exit 1, one block on stderr, report grouped by check`() {
        // (a) broken references into the hub and a satellite, incl. a line past the end; hub and sat-b targets
        // alternate, and the findings still come in line order.
        write(satA, "docs/invite/NOTE.md", note(body = "`hub/docs/gone.md`\n`sat-b/doc/index.md:99`\n`hub/docs/gone2.md`\n`hub/build/out.kt`\n"))
        write(hub, ".gitignore", "build/\n")
        // (b) a hub that does not resolve, and one that is not a Feature Record.
        write(satB, "doc/OTHER.md", note(hub = "features/gone"))
        write(satB, "doc/GUIDE_LINK.md", note(hub = "features/guide"))
        write(hub, "docs/features/guide.md", "---\ntype: Guide\n---\n# G\n")
        // (c) repos lists a satellite without a note and a non-satellite; a note whose record does not list its repo.
        write(hub, "docs/features/solo.md", record(repos = "[sat-a, legacy]"))
        write(hub, "docs/features/unlisted.md", record(repos = null))
        write(satA, "docs/UNLISTED.md", note(hub = "features/unlisted"))
        // (e) the index URL of sat-b names docs/, its docs_root is doc/.
        hub.resolve("okf.yaml").writeText(hub.resolve("okf.yaml").readText().replace("sat-b/blob/main/doc/", "sat-b/blob/main/docs/"))

        val run = xcheck()
        assertEquals(1, run.code, run.toString())
        val notFound = "— fix the path, or opt the line out with `<!-- okf: ignore-refs -->`"
        assertEquals(
            listOf(
                "okf xcheck found 9 problem(s):",
                "  - sat-a/docs/invite/NOTE.md:8: `hub/docs/gone.md`: file not found in hub $notFound",
                "  - sat-a/docs/invite/NOTE.md:9: `sat-b/doc/index.md:99`: line 99 is past the end of doc/index.md (4 lines)",
                "  - sat-a/docs/invite/NOTE.md:10: `hub/docs/gone2.md`: file not found in hub $notFound",
                "  - sat-b/doc/GUIDE_LINK.md:3: hub 'features/guide' resolves to hub/docs/features/guide.md, which is not a Feature Record " +
                    "(type 'Guide')",
                "  - sat-b/doc/OTHER.md:3: hub 'features/gone' does not resolve: hub/docs/features/gone.md does not exist",
                "  - hub/docs/features/solo.md:4: repos lists 'sat-a', but sat-a has no Satellite Note with `hub: features/solo`",
                "  - hub/docs/features/solo.md:4: repos lists 'legacy', which is not a satellite (`satellites` in hub/okf.yaml)",
                "  - sat-a/docs/UNLISTED.md:3: hub record hub/docs/features/unlisted.md does not list sat-a in `repos:`",
                "  - hub/okf.yaml:11: satellites[1].index 'https://github.com/org/sat-b/blob/main/docs/index.md' must end with /doc/index.md " +
                    "(docs_root of sat-b)",
            ),
            run.err.trim().lines(),
        )
        assertEquals(
            "okfXcheck: 3 repos checked, 5 cross-repo references checked (3 broken), 1 references to non-federated repos not checked, " +
                "3 Satellite Notes linked to 2 Feature Records; 9 problem(s), 0 warning(s).",
            run.out.trim(),
        )
        val text = report.readText()
        assertTrue(text.startsWith("# okf xcheck: 9 problem(s), 0 warning(s)\n\n"), text)
        val headings = text.lines().filter { it.startsWith("## ") }
        assertEquals(
            listOf(
                "## (a) Cross-repo references",
                "## (b) `hub:` of Satellite Notes",
                "## (c) `repos:` ↔ Satellite Notes",
                "## (e) Satellite index URLs",
            ),
            headings,
        )
        assertTrue("\n- sat-b/doc/OTHER.md:3: hub 'features/gone' does not resolve: hub/docs/features/gone.md does not exist\n" in text, text)
        assertTrue(text.endsWith("---\n\n${run.out.trim()}\n"), text)
    }

    @Test
    fun `drift of more than 14 days is a warning - exit 0, report written`() {
        write(satA, "docs/invite/NOTE.md", note(body = "Changed.\n"))
        commit(satA, "note changed", DAY_0 + 15 * DAY)
        write(satB, "doc/NOTE.md", note(body = "Changed.\n"))
        commit(satB, "note changed", DAY_0 + 14 * DAY) // exactly 14 days: not drift

        val run = xcheck()
        assertEquals(0, run.code, run.toString())
        assertEquals(
            "OKF XCHECK WARNING: hub/docs/features/invite.md:1: hub record docs/features/invite.md is 15 days older than " +
                "sat-a/docs/invite/NOTE.md — distill the satellite changes into the record",
            run.err.trim(),
        )
        assertTrue(run.out.trim().startsWith("okfXcheck OK: 3 repos checked, "), run.out)
        assertTrue(run.out.trim().endsWith("; 1 warning(s)."), run.out)
        val text = report.readText()
        assertTrue(text.startsWith("# okf xcheck: 0 problem(s), 1 warning(s)\n"), text)
        assertTrue("## (d) Drift between Satellite Notes and hub records (warnings)\n\n- hub/docs/features/invite.md:1: hub record" in text, text)

        // Updating the record clears the drift (and the report).
        write(hub, "docs/features/invite.md", record(repos = "[sat-a, sat-b]", body = "`sat-a/lib/a.kt:1-2` `legacy/x.kt` `hub/Hub.kt`\n\nDistilled.\n"))
        commit(hub, "distill", DAY_0 + 16 * DAY)
        val clean = xcheck()
        assertEquals(0, clean.code, clean.toString())
        assertEquals("", clean.err)
        assertFalse(report.exists())
    }

