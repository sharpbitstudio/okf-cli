    @Test
    fun `version and help`() {
        val version = run("version")
        assertEquals(0, version.code)
        assertTrue(version.out.startsWith("okf-cli "), version.out)
        assertTrue("unknown" !in version.out, version.out)
        // `--help` / `-h` anywhere on the line (even next to an invalid option), `help` as the command.
        val helpLines = listOf(
            listOf("--help"),
            listOf("help"),
            listOf("check", "--help"),
            listOf("impact", "--base=x", "-h"),
            listOf("index", "--bogus", "--help"),
        )
        for (args in helpLines) {
            val help = run(*args.toTypedArray())
            assertEquals(0, help.code, "$args: $help")
