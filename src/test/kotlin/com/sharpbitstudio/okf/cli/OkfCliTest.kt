    @Test
    fun `repo must be the git work-tree root`() {
        // A subdirectory holding its own okf.yaml + bundle would otherwise run against the wrong root.
        write("sub/okf.yaml", "schema_version: 1\nrepo: sub\n")
        write("sub/docs/index.md", "---\nokf_version: \"0.2\"\n---\n# Docs\n")
        for (command in listOf("index", "check", "impact")) {
            val sub = run(command, "--repo=${repo.resolve("sub").path}")
            assertEquals(2, sub.code, sub.toString())
            assertTrue(sub.err.startsWith("okf $command: --repo must be the git work-tree root ("), sub.err)
        }
        assertTrue(!repo.resolve("sub/docs/adr").exists())

        val notGit = run("check", "--repo=${home.path}")
        assertEquals(2, notGit.code, notGit.toString())
        // "not inside a git work tree" — or "inside <root>" should the temp dir sit below some repo.
        assertTrue(notGit.err.startsWith("okf check: --repo must be the git work-tree root ("), notGit.err)

        val missing = run("check", "--repo=${repo.resolve("nope").path}")
        assertEquals(2, missing.code, missing.toString())
        assertTrue("is not a directory" in missing.err, missing.err)

        // Same root spelled differently (relative, `\` vs `/`, trailing separator) is fine.
        assertEquals(0, run("index", "--repo=.").code)
        assertEquals(0, run("index", "--repo=${repo.path.replace('\\', '/')}/").code)

        // A git failure other than "not a work tree" (here an unsupported repo format) is reported as such, exit 1.
        git("config", "core.repositoryformatversion", "99")
        val broken = run("check", "--repo=${repo.path}")
        assertEquals(1, broken.code, broken.toString())
        assertTrue(broken.err.startsWith("okf check: git rev-parse --show-toplevel failed (exit 128) in "), broken.err)
    }

