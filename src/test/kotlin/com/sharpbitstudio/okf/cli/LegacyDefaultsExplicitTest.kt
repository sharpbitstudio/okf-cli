package com.sharpbitstudio.okf.cli

import com.sharpbitstudio.okf.IndexFixture
import org.junit.jupiter.api.Assertions.assertArrayEquals
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.ByteArrayOutputStream
import java.io.File
import java.io.PrintStream
import java.time.Instant

/**
 * A bundle whose indexes were written with the earlier defaults keeps them byte for byte once those defaults are set
 * explicitly. The earlier defaults are `index_language: sr`, `index_command: ./gradlew okfIndex` and an ADR index that
 * always links `adr/README.md`; [IndexFixture]'s `sr` goldens were written with them. End to end through [OkfCli]
 * against a throwaway git repo (real git); the controls show that the arms would notice a difference.
 */
class LegacyDefaultsExplicitTest {
    @TempDir
    lateinit var home: File

    @TempDir
    lateinit var repo: File

    private lateinit var globalConfig: File

    @BeforeEach
    fun setUp() {
        globalConfig = home.resolve("gitconfig").apply { writeText("") }
        val empty = home.resolve("empty").apply { writeText("") }
        git("init", "-q", "-b", "main")
        listOf(
            "user.name" to "t",
            "user.email" to "t@t",
            "commit.gpgsign" to "false",
            "core.autocrlf" to "false",
            "core.fsmonitor" to "false",
            "core.hooksPath" to home.resolve("no-hooks").path,
            // The tool's own git calls inherit the global config: keep ignore rules and attributes (filters) repo-only.
            "core.excludesFile" to empty.path,
            "core.attributesFile" to empty.path,
        ).forEach { (key, value) -> git("config", key, value) }
        IndexFixture.write(repo.resolve("docs"))
    }

    @Test
    fun `arm 1 - sr and the earlier index_command written out keep both indexes`() {
        config(LEGACY)
        assertIndexes(IndexFixture.ADR_INDEX_SR, IndexFixture.FEATURES_INDEX_SR)
        assertCheckOk()
    }

    @Test
    fun `arm 2 - adr_readme_link always keeps the README link when adr README md is absent`() {
        config(LEGACY + "adr_readme_link: always\n")
        assertTrue(repo.resolve("docs/adr/README.md").delete())
        assertIndexes(IndexFixture.ADR_INDEX_SR, IndexFixture.FEATURES_INDEX_SR)
        assertCheckOk(unmigrated = 3)
    }

    @Test
    fun `control 1 - without adr_readme_link a missing adr README md drops the link sentence`() {
        config(LEGACY)
        assertTrue(repo.resolve("docs/adr/README.md").delete())
        assertEquals(0, run("index", "--repo=${repo.path}").code)
        assertEquals(
            IndexFixture.ADR_INDEX_SR.replace(" Konvencije, template i lifecycle: [README.md](./README.md).", ""),
            repo.resolve("docs/adr/index.md").readText(),
        )
    }

    @Test
    fun `control 2 - without the explicit keys the indexes are English and name okf index`() {
        config("")
        assertEquals(0, run("index", "--repo=${repo.path}").code)
        assertEquals(IndexFixture.ADR_INDEX_EN.replace("./gradlew okfIndex", "okf index"), repo.resolve("docs/adr/index.md").readText())
    }

    @Test
    fun `arm 3 - the hub's Repos section keeps the earlier index_command`() {
        config(
            LEGACY + "external_repos: [sat-a]\nsatellites:\n" +
                "  - repo: sat-a\n    description: Satellite A\n    index: https://example.com/sat-a/docs/index.md\n",
        )
        val head = "---\nokf_version: \"0.2\"\n---\n# Docs\n\n## Repos\n\n<!-- okf:repos-start -->\n"
        val tail = "<!-- okf:repos-end -->\n"
        val rootIndex = repo.resolve("docs/index.md").apply { writeText(head + tail) }
        assertIndexes(IndexFixture.ADR_INDEX_SR, IndexFixture.FEATURES_INDEX_SR)
        assertEquals(
            head +
                "<!-- GENERATED by ./gradlew okfIndex from okf.yaml satellites — do not edit by hand. -->\n" +
                "\n" +
                "* [sat-a](https://example.com/sat-a/docs/index.md) - Satellite A\n" +
                tail,
            rootIndex.readText(),
        )
        assertCheckOk()
    }

    /** `okf index` exits 0 and writes exactly [adr] and [features]. */
    private fun assertIndexes(adr: String, features: String) {
        val index = run("index", "--repo=${repo.path}")
        assertEquals(0, index.code, index.toString())
        assertArrayEquals(adr.toByteArray(Charsets.UTF_8), repo.resolve("docs/adr/index.md").readBytes())
        assertArrayEquals(features.toByteArray(Charsets.UTF_8), repo.resolve("docs/features/index.md").readBytes())
    }

    /** Lenient `okf check` exits 0 with exactly these stdout lines (one unmigrated file fewer without `adr/README.md`) and no stderr. */
    private fun assertCheckOk(unmigrated: Int = 4) {
        val check = run("check", "--repo=${repo.path}")
        assertEquals(
            Run(
                0,
                "OKF INFO: $unmigrated files not yet migrated (no frontmatter); --strict makes them failures.\n" +
                    "OKF INFO: 8 Accepted/Resolved ADRs / Feature Records have no `code_paths`; --code-paths-required makes them failures.\n" +
                    "okfCheck OK: 11 documents with frontmatter validated, 0 code references resolved.\n",
                "",
            ),
            check,
        )
    }

    /** `okf.yaml` with `schema_version`, `repo` and [extra]. */
    private fun config(extra: String) {
        repo.resolve("okf.yaml").writeText("schema_version: 1\nrepo: test-repo\n$extra")
    }

    private data class Run(val code: Int, val out: String, val err: String)

    private fun run(vararg args: String): Run {
        val out = ByteArrayOutputStream()
        val err = ByteArrayOutputStream()
        val code = OkfCli(
            PrintStream(out, true, Charsets.UTF_8),
            PrintStream(err, true, Charsets.UTF_8),
            githubActions = false,
            now = { NOW },
        ).run(args.toList(), cwd = repo)
        fun text(stream: ByteArrayOutputStream) = stream.toString(Charsets.UTF_8).replace("\r\n", "\n")
        return Run(code, text(out), text(err))
    }

    private fun git(vararg args: String): String {
        val process = ProcessBuilder(listOf("git") + args).directory(repo).redirectErrorStream(true)
            .apply {
                environment()["GIT_CONFIG_GLOBAL"] = globalConfig.path
                environment()["GIT_CONFIG_NOSYSTEM"] = "1"
            }
            .start()
        val output = process.inputStream.bufferedReader().readText()
        check(process.waitFor() == 0) { "git ${args.joinToString(" ")} failed: $output" }
        return output.trim()
    }

    private companion object {
        val NOW: Instant = Instant.parse("2026-09-25T00:00:00Z")

        /** The earlier defaults, written out. */
        const val LEGACY = "index_language: sr\nindex_command: ./gradlew okfIndex\n"
    }
}
