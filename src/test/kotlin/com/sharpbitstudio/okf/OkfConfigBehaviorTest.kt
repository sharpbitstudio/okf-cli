package com.sharpbitstudio.okf

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File
import java.time.Instant

/** What the `okf.yaml` settings change in the checks (the defaults are covered by the other suites). */
class OkfConfigBehaviorTest {
    private val index = RepoIndex(
        listOf(
            "docs/index.md",
            "docs/guide.md",
            "proto/plaza/mobile/otp/v1/otp.proto",
            "plaza_mobile_app/lib/main.dart",
            "plaza_mobile_app/lib/features/otp/otp_screen.dart",
            "plaza_mobile_app/test/features/otp/otp_screen_test.dart",
            "plaza_mobile_app/lib/features/otp/otp_repo.dart",
            "plaza_mobile_app/test/features/otp/otp_repo.dart",
            "tool/gen/only/deep/Gen.kt",
        ),
        sourceRoots = listOf("plaza_mobile_app/lib", "plaza_mobile_app/test/", "tool/gen", "missing/root"),
        lineCounter = { if (it.endsWith(".proto")) 3 else null },
    )

    @Test
    fun `external_repos are skipped, other first segments are checked`() {
        val body = "`plaza-server-app/server/build.gradle.kts` `other-repo/README.md`\n"
        assertEquals(
            listOf("`plaza-server-app/server/build.gradle.kts`", "`other-repo/README.md`"),
            messages(body, externalRepos = emptySet()).map { it.substringBefore(':') },
        )
        assertMessages(
            messages(body, externalRepos = setOf("plaza-server-app")),
            "`other-repo/README.md`: file not found",
        )
    }

    @Test
    fun `ref_extensions make more code spans references`() {
        val body = "`otp/v1/otp.proto` `otp/v1/gone.proto` `features/otp/gone.dart`\n"
        assertMessages(messages(body))
        assertMessages(
            messages(body, refExtensions = listOf("proto", "dart")),
            "`otp/v1/gone.proto`: file not found",
            "`features/otp/gone.dart`: file not found",
        )
        // Line references work on the added extensions too.
        assertMessages(messages("`otp/v1/otp.proto:1` `otp/v1/otp.proto:9`\n", refExtensions = listOf("proto")), "line 9 is past the end of proto/plaza/mobile/otp/v1/otp.proto (3 lines)")
    }

    @Test
    fun `source_roots are package roots, with package descent, when they exist`() {
        assertEquals(
            listOf(
                "plaza_mobile_app/lib",
                "plaza_mobile_app/test",
                "plaza_mobile_app/test/features/otp",
                "tool/gen",
                "tool/gen/only/deep",
            ),
            index.packageRoots,
        )
        // Without source_roots only the convention roots count.
        assertEquals(
            listOf("server/src/main/java", "server/src/main/java/a/b"),
            RepoIndex(listOf("x/lib/A.kt", "server/src/main/java/a/b/App.java")).packageRoots,
        )
    }

    @Test
    fun `a path relative to source_roots resolves like a package path (main + test = one package)`() {
        // `features/otp/otp_repo.dart` exists under lib/ and test/: one package under the roots, an ambiguous suffix without them.
        val body = "`features/otp/otp_repo.dart` `features/gone.dart` `deep/Gen.kt`\n"
        assertMessages(messages(body, refExtensions = listOf("dart")), "`features/gone.dart`: file not found")
        val withoutRoots = RepoIndex(index.files)
        assertMessages(
            OkfRefChecker(withoutRoots, "docs", refExtensions = listOf("dart"))
                .check(listOf(RefDoc("guide.md", "---\ntype: Guide\n---\n$body")))
                .findings
                .map { it.message },
            "`features/otp/otp_repo.dart`: ambiguous: qualify the path (2 candidates",
            "`features/gone.dart`: file not found",
        )
    }

    @Test
    fun `index_command is named in the generated marker, the ADR header and the check hints`(@TempDir root: File) {
        root.resolve("index.md").writeText("---\nokf_version: \"0.2\"\n---\n# Docs\n")
        root.resolve("adr").mkdirs()
        root.resolve("features").mkdirs()
        val command = "tool/run-okf.sh index"

        val adrIndex = OkfIndexRenderer.renderAdrIndex(root.resolve("adr"), command)
        val featuresIndex = OkfIndexRenderer.renderFeaturesIndex(root.resolve("features"), command)
        assertTrue(adrIndex.startsWith("<!-- GENERATED by tool/run-okf.sh index from frontmatter — do not edit by hand. -->\n"), adrIndex)
        assertTrue("generisan iz frontmatter-a (`tool/run-okf.sh index`)" in adrIndex, adrIndex)
        assertTrue(featuresIndex.startsWith("<!-- GENERATED by tool/run-okf.sh index from frontmatter"), featuresIndex)
        assertEquals(
            "<!-- GENERATED by ./gradlew okfIndex from frontmatter — do not edit by hand. -->",
            OkfIndexRenderer.generatedMarker(),
        )

        val missing = OkfChecker.check(root, strict = true, now = NOW, indexCommand = command).problems
        assertEquals(listOf("adr/index.md: missing — run tool/run-okf.sh index", "features/index.md: missing — run tool/run-okf.sh index"), missing)

        // An index rendered with the default command is stale for a repo with another index_command.
        root.resolve("adr/index.md").writeText(OkfIndexRenderer.renderAdrIndex(root.resolve("adr")))
        root.resolve("features/index.md").writeText(featuresIndex)
        assertEquals(
            listOf("adr/index.md: out of date or edited by hand — run tool/run-okf.sh index"),
            OkfChecker.check(root, strict = true, now = NOW, indexCommand = command).problems,
        )
        root.resolve("adr/index.md").writeText(adrIndex)
        assertEquals(emptyList<String>(), OkfChecker.check(root, strict = true, now = NOW, indexCommand = command).problems)
    }

    private fun messages(body: String, externalRepos: Set<String> = emptySet(), refExtensions: List<String> = emptyList()): List<String> =
        OkfRefChecker(index, "docs", externalRepos, refExtensions)
            .check(listOf(RefDoc("guide.md", "---\ntype: Guide\n---\n$body")))
            .findings
            .map { it.message }

    private fun assertMessages(messages: List<String>, vararg expected: String) {
        assertEquals(expected.size, messages.size, "findings:\n${messages.joinToString("\n")}")
        expected.zip(messages).forEach { (fragment, message) -> assertTrue(fragment in message, "expected <$fragment> in <$message>") }
    }

    private companion object {
        val NOW: Instant = Instant.parse("2026-09-25T00:00:00Z")
    }
}
