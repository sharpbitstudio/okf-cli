            "features/plain.md" to feature(""),
            "features/with space.md" to feature("title: \"Spaced feature\"\ndescription: \"When the name has a space\"\n"),
        )
        files.forEach { (path, text) -> bundle.resolve(path).apply { parentFile.mkdirs() }.writeText(text, Charsets.UTF_8) }
    }

    private fun adr(adrStatus: String, title: String, description: String, tags: String, extra: String = "", body: String = "# ADR\n"): String {
        val status = when (adrStatus) {
            "Proposed" -> "draft"
            "Superseded", "Deprecated" -> "deprecated"
            else -> "stable"
        }
        return "---\ntype: ADR\ntitle: \"$title\"\ndescription: \"$description\"\ntags: $tags\nstatus: $status\n" +
            "adr_status: $adrStatus\nadr_date: 2026-07-01\n$extra---\n$body"
    }

    private fun feature(fields: String) = "---\ntype: Feature Record\n${fields}status: stable\n---\n# Feature\n"

