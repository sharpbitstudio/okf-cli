package com.sharpbitstudio.okf

import org.junit.jupiter.api.Assertions.assertArrayEquals
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertFalse
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.assertThrows
import org.junit.jupiter.api.io.TempDir
import java.io.File

class OkfIndexRendererTest {
    @TempDir
    lateinit var dir: File

    private val rendered = "<!-- GENERATED -->\n\n# Feature Records\n\n* [A](./a.md)\n"

    @Test
    fun `new index is written with LF`() {
        val file = dir.resolve("index.md")
        assertTrue(OkfIndexRenderer.write(file, rendered))
        assertEquals(rendered, file.readText())
    }

    @Test
    fun `unchanged index is not rewritten, whatever its line endings or BOM`() {
        for (existing in listOf(rendered, rendered.replace("\n", "\r\n"), "\uFEFF" + rendered.replace("\n", "\r\n"))) {
            val file = dir.resolve("index.md").apply { writeText(existing) }
            val bytes = file.readBytes()
            file.setLastModified(1_000_000_000_000)
            assertFalse(OkfIndexRenderer.write(file, rendered))
            assertArrayEquals(bytes, file.readBytes())
            assertEquals(1_000_000_000_000, file.lastModified())
        }
    }

    @Test
    fun `repos block renders a generated note and one link per satellite in okf yaml order`() {
        val block = OkfIndexRenderer.renderReposBlock(
            listOf(Satellite("sat-b", "Mobile app", "https://x/sat-b/docs/index.md"), Satellite("sat-a", "Proto", "https://x/sat-a/doc/index.md")),
            "tool/run-okf.sh index",
        )
        assertEquals(
            "<!-- GENERATED by tool/run-okf.sh index from okf.yaml satellites — do not edit by hand. -->\n\n" +
                "* [sat-b](https://x/sat-b/docs/index.md) - Mobile app\n* [sat-a](https://x/sat-a/doc/index.md) - Proto",
            block,
        )
    }

    @Test
    fun `repos block replaces only the lines between the markers`() {
        val text = "---\nokf_version: \"0.2\"\n---\n# Docs\n\n## Repos\n\n<!-- okf:repos-start -->\nold\n\nlines\n  <!-- okf:repos-end -->\n\nTail.\n"
        assertEquals(
            "---\nokf_version: \"0.2\"\n---\n# Docs\n\n## Repos\n\n<!-- okf:repos-start -->\nNEW\n  <!-- okf:repos-end -->\n\nTail.\n",
            OkfIndexRenderer.replaceReposBlock(text, "NEW"),
        )
        val empty = "<!-- okf:repos-start -->\n<!-- okf:repos-end -->"
        assertEquals("<!-- okf:repos-start -->\na\nb\n<!-- okf:repos-end -->", OkfIndexRenderer.replaceReposBlock(empty, "a\nb"))
    }

    @Test
    fun `repos block markers must be one start line followed by one end line`() {
        val cases = mapOf(
            "# Docs\n" to "found 0 start / 0 end marker line(s)",
            "<!-- okf:repos-start -->\n" to "found 1 start / 0 end marker line(s)",
            "<!-- okf:repos-start -->\n<!-- okf:repos-start -->\n<!-- okf:repos-end -->\n" to "found 2 start / 1 end marker line(s)",
            "<!-- okf:repos-end -->\n<!-- okf:repos-start -->\n" to "found 1 start / 1 end marker line(s), end before start",
            // A marker quoted as code or sharing its line with text is not a marker line.
            "`<!-- okf:repos-start -->`\nx <!-- okf:repos-end -->\n" to "found 0 start / 0 end marker line(s)",
        )
        for ((text, fragment) in cases) {
            val e = assertThrows<OkfException> { OkfIndexRenderer.replaceReposBlock(text, "x") }
            assertEquals(
                "index.md: the Repos section needs one `<!-- okf:repos-start -->` line followed by one `<!-- okf:repos-end -->` line ($fragment)",
                e.message,
            )
        }
    }

    @Test
    fun `repos block written over a CRLF index keeps CRLF, unchanged is not rewritten`() {
        val file = dir.resolve("index.md").apply { writeText("# Docs\r\n<!-- okf:repos-start -->\r\nold\r\n<!-- okf:repos-end -->\r\n") }
        val replaced = OkfIndexRenderer.replaceReposBlock(OkfFrontmatter.normalize(file.readText()), "* [a](https://x) - A")
        assertTrue(OkfIndexRenderer.write(file, replaced))
        assertEquals("# Docs\r\n<!-- okf:repos-start -->\r\n* [a](https://x) - A\r\n<!-- okf:repos-end -->\r\n", file.readText())
        assertFalse(OkfIndexRenderer.write(file, OkfIndexRenderer.replaceReposBlock(OkfFrontmatter.normalize(file.readText()), "* [a](https://x) - A")))
    }

    @Test
    fun `keepBom keeps a leading BOM of the rewritten file, by default it is dropped`() {
        val kept = dir.resolve("root.md").apply { writeText("﻿# Docs\r\n<!-- old -->\r\n") }
        assertTrue(OkfIndexRenderer.write(kept, "# Docs\n<!-- new -->\n", keepBom = true))
        assertEquals("﻿# Docs\r\n<!-- new -->\r\n", kept.readText())
        val dropped = dir.resolve("sub.md").apply { writeText("﻿<!-- old -->\n") }
        assertTrue(OkfIndexRenderer.write(dropped, rendered))
        assertEquals(rendered, dropped.readText())
        val created = dir.resolve("new.md")
        assertTrue(OkfIndexRenderer.write(created, rendered, keepBom = true))
        assertEquals(rendered, created.readText())
    }

    @Test
    fun `ADR index renders every section, entry form and the unmigrated list (sr text)`() {
        IndexFixture.write(dir)
        assertEquals(IndexFixture.ADR_INDEX_SR, OkfIndexRenderer.renderAdrIndex(dir.resolve(OkfIndexRenderer.ADR_DIR), TestConfigs.INDEX_COMMAND, IndexLanguage.SR, AdrReadmeLink.AUTO))
    }

    @Test
    fun `features index renders records, the title fallback and the unmigrated list (sr text)`() {
        IndexFixture.write(dir)
        assertEquals(IndexFixture.FEATURES_INDEX_SR, OkfIndexRenderer.renderFeaturesIndex(dir.resolve(OkfIndexRenderer.FEATURES_DIR), TestConfigs.INDEX_COMMAND, IndexLanguage.SR))
    }

    @Test
    fun `index_language en replaces only the title, intro, unmigrated section and entries, and the amended suffix`() {
        IndexFixture.write(dir)
        assertEquals(
            IndexFixture.ADR_INDEX_EN,
            OkfIndexRenderer.renderAdrIndex(dir.resolve(OkfIndexRenderer.ADR_DIR), TestConfigs.INDEX_COMMAND, IndexLanguage.EN, AdrReadmeLink.AUTO),
        )
        assertEquals(
            IndexFixture.FEATURES_INDEX_EN,
            OkfIndexRenderer.renderFeaturesIndex(dir.resolve(OkfIndexRenderer.FEATURES_DIR), TestConfigs.INDEX_COMMAND, IndexLanguage.EN),
        )
        // `sr` renders the `sr` text from the same fixture.
        assertEquals(IndexFixture.ADR_INDEX_SR, OkfIndexRenderer.renderAdrIndex(dir.resolve(OkfIndexRenderer.ADR_DIR), TestConfigs.INDEX_COMMAND, IndexLanguage.SR, AdrReadmeLink.AUTO))
    }

    @Test
    fun `adr_readme_link always links README md even without the file`() {
        IndexFixture.write(dir)
        dir.resolve("adr/README.md").delete()
        assertEquals(IndexFixture.ADR_INDEX_SR, renderAdr(IndexLanguage.SR, AdrReadmeLink.ALWAYS))
        assertEquals(IndexFixture.ADR_INDEX_EN, renderAdr(IndexLanguage.EN, AdrReadmeLink.ALWAYS))
    }

    @Test
    fun `adr_readme_link auto without README md drops only the link sentence`() {
        IndexFixture.write(dir)
        dir.resolve("adr/README.md").delete()
        assertEquals(
            IndexFixture.ADR_INDEX_SR.replace(" Konvencije, template i lifecycle: [README.md](./README.md).", ""),
            renderAdr(IndexLanguage.SR, AdrReadmeLink.AUTO),
        )
        assertEquals(
            IndexFixture.ADR_INDEX_EN.replace(" Conventions, template and lifecycle: [README.md](./README.md).", ""),
            renderAdr(IndexLanguage.EN, AdrReadmeLink.AUTO),
        )
    }

    // Discriminates only on a case-insensitive file system (Windows, macOS), where `File.isFile` would find `readme.md`.
    @Test
    fun `adr_readme_link auto matches the file name exactly, readme md does not link`() {
        IndexFixture.write(dir)
        dir.resolve("adr/README.md").delete()
        dir.resolve("adr/readme.md").writeText("# ADRs\n")
        assertEquals(
            IndexFixture.ADR_INDEX_EN.replace(" Conventions, template and lifecycle: [README.md](./README.md).", ""),
            renderAdr(IndexLanguage.EN, AdrReadmeLink.AUTO),
        )
    }

    @Test
    fun `adr_readme_link auto does not link a directory named README md`() {
        IndexFixture.write(dir)
        dir.resolve("adr/README.md").delete()
        dir.resolve("adr/README.md").mkdir()
        assertEquals(
            IndexFixture.ADR_INDEX_EN.replace(" Conventions, template and lifecycle: [README.md](./README.md).", ""),
            renderAdr(IndexLanguage.EN, AdrReadmeLink.AUTO),
        )
    }

    private fun renderAdr(language: IndexLanguage, readmeLink: AdrReadmeLink) =
        OkfIndexRenderer.renderAdrIndex(dir.resolve(OkfIndexRenderer.ADR_DIR), TestConfigs.INDEX_COMMAND, language, readmeLink)

    @Test
    fun `Rejected ADRs get their own section after Superseded or Deprecated, before the unmigrated list`() {
        val adrDir = dir.resolve(OkfIndexRenderer.ADR_DIR).apply { mkdirs() }
        fun adr(name: String, adrStatus: String, status: String, title: String) =
            adrDir.resolve(name).writeText(
                "---\ntype: ADR\ntitle: \"$title\"\ndescription: \"When reading $title\"\ntags: [demo]\n" +
                    "status: $status\nadr_status: $adrStatus\nadr_date: 2026-01-01\n---\n# ADR\n",
            )
        adr("ADR-001-kept.md", "Accepted", "stable", "Kept")
        adr("ADR-002-retired.md", "Deprecated", "deprecated", "Retired")
        adr("ADR-003-declined.md", "Rejected", "deprecated", "Declined")
        adrDir.resolve("ADR-004-legacy.md").writeText("# Legacy ADR\n")
        assertEquals(
            """
            |<!-- GENERATED by okf index from frontmatter — do not edit by hand. -->
            |
            |# ADR Registry
            |
            |The single ADR registry, generated from frontmatter (`okf index`) and grouped by status, with a "when to read" description and tags for each ADR.
            |
            |# Accepted
            |
            |* [ADR-001 — Kept](./ADR-001-kept.md) - When reading Kept `tags: demo`
            |
            |# Superseded / Deprecated
            |
            |* [ADR-002 — Retired](./ADR-002-retired.md) - When reading Retired `tags: demo`
            |
            |# Rejected
            |
            |* [ADR-003 — Declined](./ADR-003-declined.md) - When reading Declined `tags: demo`
            |
            |# Not migrated
            |
            |* [ADR-004](./ADR-004-legacy.md) - no frontmatter yet
            |""".trimMargin(),
            OkfIndexRenderer.renderAdrIndex(adrDir, "okf index", IndexLanguage.EN, AdrReadmeLink.AUTO),
        )
    }

    @Test
    fun `changed index keeps the existing line-ending style`() {
        val crlf = dir.resolve("crlf.md").apply { writeText("<!-- old -->\r\n") }
        assertTrue(OkfIndexRenderer.write(crlf, rendered))
        assertEquals(rendered.replace("\n", "\r\n"), crlf.readText())

        val lf = dir.resolve("lf.md").apply { writeText("<!-- old -->\n") }
        assertTrue(OkfIndexRenderer.write(lf, rendered))
        assertEquals(rendered, lf.readText())
    }
}

/**
