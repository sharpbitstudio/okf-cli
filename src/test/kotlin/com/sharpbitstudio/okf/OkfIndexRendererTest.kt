            "adr/ADR-003-resolved.md" to adr("Resolved", "Resolved question", "When it comes up again", "[ops]"),
            "adr/ADR-004-superseded.md" to
                adr("Superseded", "Old transport", "Historical only", "[grpc]", extra = "superseded_by: ./ADR-001-accepted.md\n"),
            "adr/ADR-005-deprecated.md" to adr("Deprecated", "Dropped approach", "Never", "[legacy]"),
            "adr/ADR-006-amended.md" to adr(
                "Accepted",
                "Amended decision",
                "When amending",
                "[process]",
                extra = "amended: [2026-07-05, 2026-08-10]\n",
                body = "# ADR\n\n**Update 2026-07-05:** first.\n\n**Update 2026-08-10:** second.\n",
            ),
            "adr/ADR-007-legacy.md" to "# Legacy ADR\n",
            "adr/ADR-008-with space.md" to adr("Accepted", "Spaced name", "When the name has a space", "[naming]"),
            "features/README.md" to "# Features\n",
            "features/TEMPLATE.md" to "---\ntype: Feature Record\ntitle: \"Template\"\nstatus: draft\n---\n# Template\n",
            "features/invite-respond.md" to feature("title: \"Invite respond\"\ndescription: \"When touching invites\"\ntags: [invites, push]\n"),
