package com.sharpbitstudio.okf

import java.io.File

/**
 * Renders the generated sub-indexes (`docs/adr/index.md`, `docs/features/index.md`) from
 * frontmatter, and the hub's "Repos" section of the bundle-root `index.md` from `satellites`.
 * Shared by `okf index` (writes) and `okf check` (compares), so both always agree.
 * Output is deterministic: LF line endings, single trailing newline ([write] keeps an existing file's
 * line endings). `indexCommand` is the repo's `index_command` ([OkfConfig]); it appears in the generated text.
 * `language` (`index_language`) picks the fixed text in [Texts]; everything else is the same in every language.
 */
object OkfIndexRenderer {
    /** First line of every generated index. */
    fun generatedMarker(indexCommand: String = OkfConfig.DEFAULT_INDEX_COMMAND) =
        "<!-- GENERATED by $indexCommand from frontmatter — do not edit by hand. -->"

    const val ADR_DIR = "adr"
    const val FEATURES_DIR = "features"

    /**
     * ADR file name (`ADR-NNN-<slug>.md`, three-digit number in group 1) — the single definition
     * of ADR identity, shared with [OkfChecker] so the index and the checker always agree.
     */
    val ADR_FILE = Regex("""ADR-(\d{3})-[^/]+\.md""")
    private val NON_ENTRIES = OkfFrontmatter.RESERVED + setOf("README.md", "TEMPLATE.md")

    /** `adr_status` value → index section; sections render in this order, empty ones are omitted. */
    private val ADR_SECTIONS = linkedMapOf(
        "Accepted" to "Accepted",
        "Proposed" to "Proposed",
        "Resolved" to "Resolved",
        "Superseded" to "Superseded / Deprecated",
        "Deprecated" to "Superseded / Deprecated",
    )

    /**
     * The fixed text of the generated indexes that depends on `index_language`. Everything else (marker line,
     * status headings, "Feature Records", entry format, the Repos section) is the same in every language.
     */
    private class Texts(
        val adrTitle: String,
        /** The ADR index intro, around the `index_command`. */
        val adrIntro: (indexCommand: String) -> String,
        val unmigratedSection: String,
        val unmigratedEntry: String,
        val amended: (date: String) -> String,
    )

    /** Exhaustive over [IndexLanguage]: a new language does not compile without its texts. */
    private fun texts(language: IndexLanguage): Texts =
        when (language) {
            IndexLanguage.SR -> SR_TEXTS
            IndexLanguage.EN -> EN_TEXTS
        }

    private val SR_TEXTS =
        Texts(
            adrTitle = "# ADR Registar",
            adrIntro = { indexCommand ->
                "Jedini registar ADR-ova — generisan iz frontmatter-a (`$indexCommand`), grupisan po " +
                    "statusu, sa „kada čitati\" opisom i tagovima uz svaki ADR. Konvencije, template i lifecycle: " +
                    "[README.md](./README.md)."
            },
            unmigratedSection = "Nije migrirano",
            unmigratedEntry = " - još bez frontmatter-a",
            amended = { " (izmenjeno $it)" },
        )

    private val EN_TEXTS =
        Texts(
            adrTitle = "# ADR Registry",
            adrIntro = { indexCommand ->
                "The single ADR registry, generated from frontmatter (`$indexCommand`) and grouped by status, " +
                    "with a \"when to read\" description and tags for each ADR. Conventions, template and lifecycle: " +
                    "[README.md](./README.md)."
            },
            unmigratedSection = "Not migrated",
            unmigratedEntry = " - no frontmatter yet",
            amended = { " (amended $it)" },
        )

    fun renderAdrIndex(
        adrDir: File,
        indexCommand: String = OkfConfig.DEFAULT_INDEX_COMMAND,
        language: IndexLanguage = IndexLanguage.SR,
    ): String {
        val texts = texts(language)
        val adrs = markdownFiles(adrDir)
            .mapNotNull { file -> ADR_FILE.matchEntire(file.name)?.let { file to it.groupValues[1] } }
            .sortedWith(compareBy({ it.second.toInt() }, { it.first.name }))

        val sections = linkedMapOf<String, MutableList<String>>()
        ADR_SECTIONS.values.distinct().forEach { sections[it] = mutableListOf() }
        val unmigrated = mutableListOf<String>()

        for ((file, number) in adrs) {
            when (val fm = readForIndex(file)) {
                Frontmatter.Absent -> unmigrated += "* [ADR-$number](${href(file)})${texts.unmigratedEntry}"
                is Frontmatter.Present -> {
                    val adrStatus = fm.string("adr_status")
                    val section = ADR_SECTIONS[adrStatus]
                        ?: throw OkfException("$ADR_DIR/${file.name}: unknown or missing adr_status '$adrStatus'")
                    // `amended` is ascending (okf check enforces it); the index shows the latest amendment.
                    val amendedSuffix = (fm.data["amended"] as? List<*>)?.mapNotNull { it?.toString() }?.maxOrNull()
                        ?.let(texts.amended).orEmpty()
                    var line = entry(
                        "ADR-$number — ${fm.string("title") ?: file.nameWithoutExtension}",
                        href(file),
                        fm,
                        afterLink = amendedSuffix,
                    )
                    if (adrStatus == "Superseded") {
                        fm.string("superseded_by")?.let { target ->
                            val targetNumber = ADR_FILE.matchEntire(target.substringAfterLast('/'))?.groupValues?.get(1)
                            line += " → [${targetNumber?.let { "ADR-$it" } ?: target}]($target)"
                        }
                    }
                    sections.getValue(section) += line
                }
                is Frontmatter.Invalid -> error("unreachable")
            }
        }

        return render(
            header = listOf(texts.adrTitle, "", texts.adrIntro(indexCommand)),
            sections = sections + (texts.unmigratedSection to unmigrated),
            indexCommand = indexCommand,
        )
    }

    fun renderFeaturesIndex(
        featuresDir: File,
        indexCommand: String = OkfConfig.DEFAULT_INDEX_COMMAND,
        language: IndexLanguage = IndexLanguage.SR,
    ): String {
        val texts = texts(language)
        val records = mutableListOf<String>()
        val unmigrated = mutableListOf<String>()
        for (file in markdownFiles(featuresDir).filter { it.name !in NON_ENTRIES }) {
            when (val fm = readForIndex(file)) {
                Frontmatter.Absent ->
                    unmigrated += "* [${file.nameWithoutExtension}](${href(file)})${texts.unmigratedEntry}"
                is Frontmatter.Present -> records += entry(fm.string("title") ?: file.nameWithoutExtension, href(file), fm)
                is Frontmatter.Invalid -> error("unreachable")
            }
        }
        return render(
            header = emptyList(),
            sections = linkedMapOf("Feature Records" to records, texts.unmigratedSection to unmigrated),
            indexCommand = indexCommand,
        )
    }

    /** Marker lines around the generated "Repos" section of the hub's bundle-root `index.md` ([replaceReposBlock]). */
    const val REPOS_START = "<!-- okf:repos-start -->"
    const val REPOS_END = "<!-- okf:repos-end -->"

    /**
     * The "Repos" section body (the lines between [REPOS_START] and [REPOS_END], LF, no trailing newline):
     * a generated note, then one link per satellite to its bundle-root `index.md`, in `okf.yaml` order.
     * The heading above the start marker is the repo's own text.
     */
    fun renderReposBlock(satellites: List<Satellite>, indexCommand: String = OkfConfig.DEFAULT_INDEX_COMMAND): String =
        (listOf("<!-- GENERATED by $indexCommand from okf.yaml satellites — do not edit by hand. -->", "") +
            satellites.map { "* [${it.repo}](${it.index}) - ${it.description}" }).joinToString("\n")

    /**
     * [indexText] (LF-normalized, [OkfFrontmatter.normalize]) with everything strictly between the [REPOS_START] and
     * [REPOS_END] lines replaced by [block]; the rest of the text is kept as is. Throws [OkfException] unless the
     * text has exactly one start line followed by exactly one end line (a marker line holds only the marker).
     */
    fun replaceReposBlock(indexText: String, block: String): String {
        val lines = indexText.split('\n')
        val starts = lines.indices.filter { lines[it].trim() == REPOS_START }
        val ends = lines.indices.filter { lines[it].trim() == REPOS_END }
        if (starts.size != 1 || ends.size != 1 || starts.single() > ends.single()) {
            val found = "found ${starts.size} start / ${ends.size} end marker line(s)" +
                if (starts.size == 1 && ends.size == 1) ", end before start" else ""
            throw OkfException(
                "index.md: the Repos section needs one `$REPOS_START` line followed by one `$REPOS_END` line ($found)",
            )
        }
        return (lines.subList(0, starts.single() + 1) + block.split('\n') + lines.subList(ends.single(), lines.size)).joinToString("\n")
    }

    /**
     * Writes a [rendered] index to [file] without creating spurious changes: an existing file whose content
     * equals [rendered] once BOM and line endings are normalized ([OkfFrontmatter.normalize], the same
     * comparison `okf check` makes) is left untouched; an existing file is rewritten in its own line-ending
     * style (CRLF when it contains any CRLF, else LF), so a `core.autocrlf=true` checkout does not show
     * an EOL-only modification; a new file gets LF. [keepBom] keeps an existing file's UTF-8 BOM (the hub's
     * hand-written root index.md, of which only the "Repos" section is generated). Returns whether the file was written.
     */
    fun write(file: File, rendered: String, keepBom: Boolean = false): Boolean {
        val existing = if (file.isFile) file.readText(Charsets.UTF_8) else null
        if (existing != null && OkfFrontmatter.normalize(existing) == rendered) return false
        val eol = if (existing != null && "\r\n" in existing) "\r\n" else "\n"
        val bom = if (keepBom && existing != null && existing.startsWith(BOM)) BOM else ""
        file.writeText(bom + rendered.replace("\n", eol), Charsets.UTF_8)
        return true
    }

    private const val BOM = "\uFEFF"

    private fun markdownFiles(dir: File): List<File> =
        (dir.listFiles() ?: emptyArray()).filter { it.isFile && it.extension == "md" }.sortedBy { it.name }

    private fun readForIndex(file: File): Frontmatter =
        OkfFrontmatter.read(file).also {
            if (it is Frontmatter.Invalid) throw OkfException("${file.parentFile.name}/${file.name}: ${it.reason}")
        }

    private fun entry(title: String, href: String, fm: Frontmatter.Present, afterLink: String = ""): String {
        val details = listOfNotNull(
            fm.string("description"),
            fm.tags().takeIf { it.isNotEmpty() }?.let { "`tags: ${it.joinToString(", ")}`" },
        )
        return "* [$title]($href)$afterLink" + if (details.isEmpty()) "" else " - " + details.joinToString(" ")
    }

    private fun href(file: File) = "./" + file.name.replace(" ", "%20")

    private fun render(header: List<String>, sections: Map<String, List<String>>, indexCommand: String): String {
        val blocks = mutableListOf(listOf(generatedMarker(indexCommand)))
        if (header.isNotEmpty()) blocks += header
        sections.filterValues { it.isNotEmpty() }.forEach { (title, entries) -> blocks += listOf("# $title", "") + entries }
        return blocks.joinToString("\n\n") { it.joinToString("\n") } + "\n"
    }
}
